class Calculadora {
    sumar(num1, num2) {
        return num1 + num2;
    }

    restar(num1, num2) {
        return num1 - num2;
    }

    dividir(num1, num2) {
        return num1 / num2;
    }

    multiplicar(num1, num2) {
        return num1 * num2;
    }

    raizCuadrada(num) {
        return Math.sqrt(num);
    }

    potenciaCuadrado(num) {
        return Math.pow(num, 2);
    }
}